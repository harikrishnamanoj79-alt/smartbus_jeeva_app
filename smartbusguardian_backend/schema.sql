-- ============================================================
-- SmartBus Guardian Database Schema
-- Database: SQLite
-- Based on: Smart_Bus_Synopsis.docx table design
-- ============================================================

PRAGMA foreign_keys = ON;

-- 1. tbl_users
-- Stores registered passenger account details used for authentication
-- and profile management.
CREATE TABLE IF NOT EXISTS tbl_users (
    user_id        INTEGER PRIMARY KEY AUTOINCREMENT,
    full_name      TEXT NOT NULL,
    email          TEXT UNIQUE NOT NULL,
    phone_number   TEXT UNIQUE NOT NULL,
    password_hash  TEXT NOT NULL,
    created_at     DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 2. tbl_saved_destinations
-- Stores frequently visited destinations saved by a user for quick selection.
CREATE TABLE IF NOT EXISTS tbl_saved_destinations (
    destination_id    INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id           INTEGER NOT NULL,
    destination_name  TEXT NOT NULL,
    latitude          REAL NOT NULL,
    longitude         REAL NOT NULL,
    FOREIGN KEY (user_id) REFERENCES tbl_users (user_id)
        ON DELETE CASCADE
);

-- 3. tbl_journey
-- Records details of each ongoing or completed journey undertaken
-- by a passenger.
CREATE TABLE IF NOT EXISTS tbl_journey (
    journey_id             INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id                INTEGER NOT NULL,
    source_location        TEXT NOT NULL,
    destination_location   TEXT NOT NULL,
    dest_latitude          REAL NOT NULL,
    dest_longitude         REAL NOT NULL,
    sleep_mode_enabled     BOOLEAN DEFAULT 0,
    start_time             DATETIME NOT NULL,
    end_time               DATETIME,
    journey_status         TEXT DEFAULT 'ONGOING'
        CHECK (journey_status IN ('ONGOING', 'COMPLETED', 'MISSED')),
    FOREIGN KEY (user_id) REFERENCES tbl_users (user_id)
        ON DELETE CASCADE
);

-- 4. tbl_alerts
-- Logs each alert generated by the Smart Destination Alert and
-- Sleep Protection modules.
CREATE TABLE IF NOT EXISTS tbl_alerts (
    alert_id            INTEGER PRIMARY KEY AUTOINCREMENT,
    journey_id          INTEGER NOT NULL,
    alert_type          TEXT NOT NULL
        CHECK (alert_type IN ('VOICE', 'VIBRATION', 'ALARM', 'SCREEN')),
    distance_remaining  REAL NOT NULL,
    triggered_at        DATETIME DEFAULT CURRENT_TIMESTAMP,
    acknowledged        BOOLEAN DEFAULT 0,
    FOREIGN KEY (journey_id) REFERENCES tbl_journey (journey_id)
        ON DELETE CASCADE
);

-- 5. tbl_missed_stop
-- Stores records generated by the Missed-Stop Detection module when
-- a passenger crosses their destination.
CREATE TABLE IF NOT EXISTS tbl_missed_stop (
    missed_id            INTEGER PRIMARY KEY AUTOINCREMENT,
    journey_id           INTEGER NOT NULL,
    missed_latitude      REAL NOT NULL,
    missed_longitude     REAL NOT NULL,
    nearest_return_stop  TEXT NOT NULL,
    alternate_route      TEXT,
    detected_at          DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (journey_id) REFERENCES tbl_journey (journey_id)
        ON DELETE CASCADE
);

-- 6. tbl_emergency_contact
-- Stores trusted contacts to be notified through the Emergency SOS module.
CREATE TABLE IF NOT EXISTS tbl_emergency_contact (
    contact_id     INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id        INTEGER NOT NULL,
    contact_name   TEXT NOT NULL,
    contact_phone  TEXT NOT NULL,
    relationship   TEXT,
    FOREIGN KEY (user_id) REFERENCES tbl_users (user_id)
        ON DELETE CASCADE
);

-- 7. tbl_sos_alert
-- Logs each SOS event raised by a passenger, including the shared
-- location and status.
CREATE TABLE IF NOT EXISTS tbl_sos_alert (
    sos_id      INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id     INTEGER NOT NULL,
    journey_id  INTEGER NOT NULL,
    latitude    REAL NOT NULL,
    longitude   REAL NOT NULL,
    sent_at     DATETIME DEFAULT CURRENT_TIMESTAMP,
    status      TEXT DEFAULT 'SENT'
        CHECK (status IN ('SENT', 'DELIVERED', 'FAILED')),
    FOREIGN KEY (user_id) REFERENCES tbl_users (user_id)
        ON DELETE CASCADE,
    FOREIGN KEY (journey_id) REFERENCES tbl_journey (journey_id)
        ON DELETE CASCADE
);

-- 8. tbl_journey_history
-- Maintains a summarized record of completed journeys for the Journey
-- History and Analytics module.
CREATE TABLE IF NOT EXISTS tbl_journey_history (
    history_id           INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id              INTEGER NOT NULL,
    journey_id           INTEGER NOT NULL,
    distance_travelled   REAL NOT NULL,
    travel_duration      TEXT NOT NULL,
    missed_stop_count    INTEGER DEFAULT 0,
    FOREIGN KEY (user_id) REFERENCES tbl_users (user_id)
        ON DELETE CASCADE,
    FOREIGN KEY (journey_id) REFERENCES tbl_journey (journey_id)
        ON DELETE CASCADE
);

-- ============================================================
-- Helpful indexes (not in the synopsis, added for performance)
-- ============================================================
CREATE INDEX IF NOT EXISTS idx_journey_user ON tbl_journey(user_id);
CREATE INDEX IF NOT EXISTS idx_alerts_journey ON tbl_alerts(journey_id);
CREATE INDEX IF NOT EXISTS idx_missed_journey ON tbl_missed_stop(journey_id);
CREATE INDEX IF NOT EXISTS idx_sos_user ON tbl_sos_alert(user_id);
CREATE INDEX IF NOT EXISTS idx_history_user ON tbl_journey_history(user_id);